export type App = {
  slug: string;
  name: string;
  /** 카드에 한 줄로 붙는 부제 */
  subtitle: string;
  /** 목록·검색에 쓰는 요약 (1~2문장) */
  summary: string;
  /** 이 앱이 답하는 질문 */
  question: string;
  /** 분류 표기 */
  kind: string;
  /** 만든 시기 */
  madeIn: string;
  /** 상태 표기 */
  status: AppStatus;
  /** 소개 페이지 상단의 한 줄 요약 */
  oneLine: string;
  /** 만든 이유 */
  why: string[];
  /** 주요 기능 */
  features: { title: string; body: string }[];
  /** 누구에게 쓸모가 있는지 */
  audience: string;
  /** 계산·판단의 기준과 출처 */
  basis?: string[];
  /** 실행 화면 입력 항목 */
  inputs?: string[];
  /** 실행 화면에서 보는 값 */
  outputs?: string[];
  /** 실행 화면 상단 한 줄 요약 */
  runNote?: string;
  /** 실행 화면에 붙는 기준일·출처 한 줄 */
  sourceLine?: string;
  /** 계산의 전제 — 결과를 읽을 때 함께 봐야 하는 가정 */
  assumptions?: string[];
  /** 외부 앱 주소 */
  externalUrl?: string;
  /**
   * 독자 범위.
   *  - reader(기본): 일반 독자용 앱스토어에 그대로 소개한다.
   *  - practitioner: 설계사현장 상담용처럼 실무자 도구라 일반 목록과 섞지 않고
   *    앱스토어 맨 아래 '실무자용' 칸에서만 소개한다.
   */
  scope?: "reader" | "practitioner";
  /** 내부 실행 앱 여부 (실행 화면이 있는 앱) */
  internal?: boolean;
  /** 카드·상세에서 함께 읽는 고지 (필요한 앱만) */
  notice?: string;
  /** 앱스토어 주제 카테고리 (APP_CATEGORIES의 id) */
  category: AppCategoryId;
  /** 카드 아트 종류 */
  art:
    | "guide"
    | "coverage"
    | "disclosure"
    | "silson"
    | "pension"
    | "pension-draw"
    | "retirement"
    | "compound"
    | "accounts"
    | "timemachine";
  /** 관련 글 태그 (검색 보조) */
  tags: string[];
};

